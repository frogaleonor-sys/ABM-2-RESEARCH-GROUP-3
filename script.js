let currentBookKey = "";
let currentPageIndex = 0;


/* =====================================================
   OPEN BOOK
===================================================== */

function openBook(key) {

    if (!libraryDatabase[key]) {

        console.error(
            "Book not found:",
            key
        );

        return;
    }

    currentBookKey = key;

    currentPageIndex = 0;

    updateReaderUI();

    const reader =
        document.getElementById("readerUI");

    reader.style.display = "block";
}


/* =====================================================
   UPDATE READER
===================================================== */

function updateReaderUI() {

    const book =
        libraryDatabase[currentBookKey];

    if (!book) return;


    document.getElementById(
        "bookTitle"
    ).innerText = book.title;


    document.getElementById(
        "bookPages"
    ).innerText =
        book.pages[currentPageIndex];


    document.getElementById(
        "pageNumber"
    ).innerText =
        `${currentPageIndex + 1} / ${book.pages.length}`;


    document.getElementById(
        "bookPages"
    ).scrollTop = 0;


    /* Button states */

    const prev =
        document.getElementById("prevButton");

    const next =
        document.getElementById("nextButton");


    prev.style.opacity =
        currentPageIndex === 0
            ? "0.5"
            : "1";


    next.style.opacity =
        currentPageIndex === book.pages.length - 1
            ? "0.5"
            : "1";
}


/* =====================================================
   NEXT PAGE
===================================================== */

function nextPage() {

    const book =
        libraryDatabase[currentBookKey];

    if (!book) return;


    if (
        currentPageIndex <
        book.pages.length - 1
    ) {

        currentPageIndex++;

        updateReaderUI();
    }
}


/* =====================================================
   PREVIOUS PAGE
===================================================== */

function prevPage() {

    if (currentPageIndex > 0) {

        currentPageIndex--;

        updateReaderUI();
    }
}


/* =====================================================
   CLOSE BOOK
===================================================== */

function closeBook() {

    document.getElementById(
        "readerUI"
    ).style.display = "none";
}


/* =====================================================
   KEYBOARD CONTROLS
===================================================== */

document.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "Escape") {

            closeBook();

        }

        if (event.key === "ArrowRight") {

            nextPage();

        }

        if (event.key === "ArrowLeft") {

            prevPage();

        }

    }
);


/* =====================================================
   SAFETY: CLOSE WHEN CLICKING OUTSIDE
===================================================== */

document.addEventListener(
    "click",
    function(event) {

        const reader =
            document.getElementById("readerUI");

        if (
            reader.style.display === "block" &&
            event.target === reader
        ) {

            closeBook();

        }

    }
);
